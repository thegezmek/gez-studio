/** Normalize every icon into a shared 0–100 HUD canvas for consistent on-screen size. */
function normalizeForHud(pathInput, paddingRatio = 0.12) {
  const pathList = Array.isArray(pathInput) ? pathInput : [pathInput];
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;

  for (const pathD of pathList) {
    const [x0, y0, x1, y1] = svgPathBbox(pathD);
    minX = Math.min(minX, x0);
    minY = Math.min(minY, y0);
    maxX = Math.max(maxX, x1);
    maxY = Math.max(maxY, y1);
  }

  const width = maxX - minX || 1;
  const height = maxY - minY || 1;
  const maxDim = Math.max(width, height);
  const hudPad = 100 * paddingRatio;
  const contentSize = 100 - hudPad * 2;
  const scale = contentSize / maxDim;
  const tx = hudPad - minX * scale + (contentSize - width * scale) / 2;
  const ty = hudPad - minY * scale + (contentSize - height * scale) / 2;

  const transform = `translate(${tx.toFixed(3)} ${ty.toFixed(3)}) scale(${scale.toFixed(6)})`;

  if (pathList.length === 1) {
    return { viewBox: "0 0 100 100", transform, path: pathList[0] };
  }

  return { viewBox: "0 0 100 100", transform, paths: pathList };
}

function findLocation(id) {
  return world.locations.find((location) => location.id === id);
}

const shapes = {};

for (const [key, id] of Object.entries(COUNTRY_IDS)) {
  const location = findLocation(id);
  if (!location) {
    throw new Error(`Missing world location: ${id} (${key})`);
  }
  shapes[key] = normalizeForHud(location.path);
}

const africaPaths = AFRICA_IDS.map((id) => findLocation(id)?.path).filter(Boolean);
if (africaPaths.length === 0) {
  throw new Error("No Africa paths found");
}

shapes.africa = normalizeForHud(africaPaths);

shapes.globe = normalizeForHud(
  "M12 2.25c5.385 0 9.75 4.365 9.75 9.75S17.385 21.75 12 21.75 2.25 17.385 2.25 12 6.615 2.25 12 2.25Zm0 0v19.5M2.25 12h19.5M5.1 7.05c2.55 1.2 4.65 1.2 6.9 0 2.25-1.2 4.35-1.2 6.9 0M5.1 16.95c2.55-1.2 4.65-1.2 6.9 0 2.25 1.2 4.35 1.2 6.9 0",
);

const output = `/* Auto-generated by scripts/export-country-geo-paths.mjs — do not edit manually */\n\nimport type { CountryGeoKey } from "./country-geo";\n\nexport type CountryGeoShape = {\n  viewBox: string;\n  transform?: string;\n  path?: string;\n  paths?: string[];\n};\n\nexport const COUNTRY_GEO_SHAPES: Record<CountryGeoKey, CountryGeoShape> = ${JSON.stringify(shapes, null, 2)};\n`;

fs.writeFileSync(
  path.join(__dirname, "../src/data/country-geo-shapes.ts"),
  output,
);

